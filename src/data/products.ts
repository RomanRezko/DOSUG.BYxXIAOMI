// Детерминированный набор магазинов и цен для каждого товара
const ALL_STORE_IDS = Object.keys(partners);

function priceForPartner(base: number, productId: string, partnerId: string): number {
  if (partnerId === 'xistore') return base;
  const seed = [...(productId + partnerId)].reduce((a, c) => a + c.charCodeAt(0), 0);
  const pct = ((seed % 13) - 6) / 100;
  return Math.round(base * (1 + pct));
}

function pickStores(productId: string): string[] {
  const seed = [...productId].reduce((a, c) => a + c.charCodeAt(0), 0);
  const count = 3 + (seed % 7); // 3..9
  const start = seed % ALL_STORE_IDS.length;
  const rotated = [...ALL_STORE_IDS.slice(start), ...ALL_STORE_IDS.slice(0, start)];
  const picked = rotated.slice(0, count);
  if (!picked.includes('xistore')) picked[0] = 'xistore';
  return picked;
}

// Детерминированный рейтинг товара в конкретном магазине: 4.3–5.0
function ratingForPartner(productId: string, partnerId: string): number {
  const seed = [...(productId + '|' + partnerId)].reduce((a, c) => a + c.charCodeAt(0), 0);
  return Math.round((4.3 + (seed % 8) * 0.1) * 10) / 10;
}

for (const product of products) {
  product.offers = pickStores(product.id).map((id) => ({
    partnerId: id,
    url: partners[id].homepage,
    price: priceForPartner(product.price, product.id, id),
    rating: ratingForPartner(product.id, id),
  }));
  // Рейтинг товара = средний рейтинг по магазинам
  const rs = product.offers.map((o) => o.rating as number);
  if (rs.length) {
    product.rating = Math.round((rs.reduce((a, b) => a + b, 0) / rs.length) * 10) / 10;
  }
}
